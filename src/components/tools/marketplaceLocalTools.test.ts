import { beforeAll, describe, expect, it, vi } from "vitest";
import { createHash, webcrypto } from "node:crypto";
import { TextDecoder, TextEncoder } from "node:util";
import JSZip from "jszip";
import { jsPDF } from "jspdf";
import { analyzeDocument, analyzeHar, marketplaceLocalTools } from "./marketplaceLocalTools";

beforeAll(() => {
  vi.stubGlobal("crypto", webcrypto);
  vi.stubGlobal("TextDecoder", TextDecoder);
  vi.stubGlobal("TextEncoder", TextEncoder);
});

function tool(id: string) {
  const implementation = marketplaceLocalTools.find(tool => tool.id === id);
  if (!implementation) throw new Error(`Missing implementation ${id}`);
  return implementation;
}

describe("honest name permutations", () => {
  it("only derives username candidates from the supplied spelling and suffixes", async () => {
    const result = await tool("username-permutator").process({ first_name: "José", last_name: "Smith", suffixes: "42,42" });
    const candidates = result.details.candidates as string[];
    expect(candidates).toContain("jose.smith42");
    expect(new Set(candidates).size).toBe(candidates.length);
    expect(result.details.verification_status).toBe("not_checked");
    expect(result.details.verified_accounts).toEqual([]);
    expect(candidates.every(candidate => !/\d/.test(candidate) || candidate.endsWith("42"))).toBe(true);
  });

  it("rejects unprovided names and invalid suffixes instead of generating invented identities", async () => {
    await expect(tool("username-permutator").process({ first_name: "", last_name: "Smith" })).rejects.toThrow("First name");
    await expect(tool("username-permutator").process({ first_name: "Jane", last_name: "Smith", suffixes: "../../secret" })).rejects.toThrow("suffixes");
  });

  it("marks email candidates unverified and rejects URL-shaped domains", async () => {
    const result = await tool("email-permutator").process({ first_name: "Jane", last_name: "Smith", domain: "Example.COM" });
    expect(result.details.candidates).toContain("jane.smith@example.com");
    expect(result.details.verified_addresses).toEqual([]);
    await expect(tool("email-permutator").process({ first_name: "Jane", last_name: "Smith", domain: "https://example.com" })).rejects.toThrow("domain");
  });
});

describe("real HAR observations", () => {
  const har = {
    log: {
      version: "1.2",
      entries: [
        {
          startedDateTime: "2026-10-12T12:00:00.000Z", time: 120.5, serverIPAddress: "203.0.113.7",
          request: { method: "GET", url: "https://example.com/data?token=secret", bodySize: -1, headers: [{ name: "Authorization", value: "secret" }] },
          response: { status: 200, bodySize: 1200, content: { size: 1500, mimeType: "application/json" } }, timings: { wait: 100, dns: -1, receive: 20.5 },
        },
        { request: { method: "POST", url: "https://example.org/fail", bodySize: 12 }, response: { status: 503, bodySize: -1 }, time: -1 },
      ],
    },
  };

  it("preserves actual hosts, IPs, status and unknown metrics without leaking header credentials", () => {
    const result = analyzeHar(JSON.stringify(har));
    expect(result.details.hosts).toEqual({ "example.com": 1, "example.org": 1 });
    expect(result.details.statuses).toEqual({ "200": 1, "503": 1 });
    expect(result.details.observed_server_ips).toEqual(["203.0.113.7"]);
    expect(result.details.observed_response_body_bytes).toBe(1200);
    const requests = result.details.requests as { elapsed_ms: number | null; request_body_bytes: number | null; query_parameter_names: string[] }[];
    expect(requests[0].query_parameter_names).toEqual(["token"]);
    expect(requests[0].request_body_bytes).toBeNull();
    expect(requests[1].elapsed_ms).toBeNull();
    expect(JSON.stringify(result)).not.toContain("secret");
  });

  it("fails malformed captures with the failing entry rather than silently making data up", () => {
    expect(() => analyzeHar("not json")).toThrow("valid JSON");
    expect(() => analyzeHar(JSON.stringify({ log: { entries: [{ request: { url: "https://example.com", method: "GET" } }] } }))).toThrow("entry 1");
    expect(() => analyzeHar(JSON.stringify({ log: { entries: [] } }))).toThrow("between 1");
  });
});

describe("document bytes and metadata", () => {
  it("extracts metadata and a real SHA-256 from a PDF generated by jsPDF", async () => {
    const pdf = new jsPDF();
    pdf.setProperties({ title: "Quarterly (field) report", author: "Supplied Author", subject: "Evidence input" });
    pdf.text("Actual test document", 10, 20);
    const bytes = new Uint8Array(pdf.output("arraybuffer"));
    const result = await analyzeDocument(Buffer.from(bytes).toString("base64"), "evidence.pdf");
    expect(result.details.format).toBe("PDF");
    expect(result.details.sha256).toBe(createHash("sha256").update(bytes).digest("hex"));
    expect(result.details.metadata).toMatchObject({ Title: "Quarterly (field) report", Author: "Supplied Author" });
    expect(result.details.visible_page_object_count).toBe(1);
  });

  it("reads actual OOXML properties, links and text with bounded ZIP expansion", async () => {
    const zip = new JSZip();
    zip.file("[Content_Types].xml", '<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types"><Default Extension="xml" ContentType="application/xml"/></Types>');
    zip.file("docProps/core.xml", '<cp:coreProperties xmlns:cp="http://schemas.openxmlformats.org/package/2006/metadata/core-properties" xmlns:dc="http://purl.org/dc/elements/1.1/"><dc:creator>Jane Smith</dc:creator><dc:title>Actual document title</dc:title></cp:coreProperties>');
    zip.file("word/document.xml", '<w:document xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main"><w:body><w:p><w:r><w:t>Supplied document text</w:t></w:r></w:p></w:body></w:document>');
    zip.file("word/_rels/document.xml.rels", '<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships"><Relationship Id="rId2" Type="hyperlink" TargetMode="External" Target="https://example.com/source"/></Relationships>');
    const bytes = await zip.generateAsync({ type: "uint8array", compression: "DEFLATE" });
    const result = await analyzeDocument(Buffer.from(bytes).toString("base64"), "evidence.docx");
    expect(result.details.format).toBe("Word OOXML");
    expect(result.details.core_metadata).toMatchObject({ "dc:creator": ["Jane Smith"], "dc:title": ["Actual document title"] });
    expect(result.details.external_relationships).toEqual([expect.objectContaining({ target: "https://example.com/source" })]);
    expect(result.details.text_excerpts).toEqual([expect.objectContaining({ text: "Supplied document text", truncated: false })]);
  });

  it("rejects unsupported bytes, corrupt ZIP and malformed metadata", async () => {
    await expect(analyzeDocument("$$notbase64")).rejects.toThrow("base64");
    await expect(analyzeDocument(Buffer.from("not a document").toString("base64"))).rejects.toThrow("Unsupported document signature");
    await expect(analyzeDocument(Buffer.from("PK broken zip").toString("base64"))).rejects.toThrow("central directory");
  });

  it("rejects an OOXML decompression bomb before inflating its content", async () => {
    const zip = new JSZip();
    zip.file("[Content_Types].xml", "<Types />");
    zip.file("word/document.xml", "A".repeat(4 * 1024 * 1024 + 1));
    const bytes = await zip.generateAsync({ type: "uint8array", compression: "DEFLATE" });
    await expect(analyzeDocument(Buffer.from(bytes).toString("base64"))).rejects.toThrow("per-part");
  });

  it("rejects a forged ZIP expanded-size declaration while streaming", async () => {
    const zip = new JSZip();
    zip.file("[Content_Types].xml", "<Types />");
    zip.file("word/document.xml", "A".repeat(100000));
    const bytes = await zip.generateAsync({ type: "uint8array", compression: "DEFLATE" });
    const view = new DataView(bytes.buffer, bytes.byteOffset, bytes.byteLength);
    for (let position = 0; position < bytes.length - 46; position++) {
      if (view.getUint32(position, true) !== 0x02014b50) continue;
      const nameLength = view.getUint16(position + 28, true);
      if (new TextDecoder().decode(bytes.subarray(position + 46, position + 46 + nameLength)) === "word/document.xml") view.setUint32(position + 24, 10, true);
    }
    await expect(analyzeDocument(Buffer.from(bytes).toString("base64"))).rejects.toThrow(/declared size|size mismatch/i);
  });
});
